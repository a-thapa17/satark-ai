export function localizeCallResult(
  result: CallCheckResult,
  language: Language
): CallCheckResult {
  if (language === "en") return result;
  const copy = HELP_COPY.hi.phone;
  const explanation =
    result.number.status === "valid"
      ? copy.numberExplanations.valid
      : result.number.status === "invalid"
        ? copy.numberExplanations.invalid
        : copy.numberExplanations.not_provided;
  const lineTypes = copy.lineTypes as Record<string, string>;
  return {
    ...result,
    number: {
      ...result.number,
      explanation,
      lineType:
        result.number.lineType && lineTypes[result.number.lineType]
          ? lineTypes[result.number.lineType]
          : result.number.lineType,
    },
    signals: result.signals.map((signal) => ({
      ...signal,
      label: PHONE_SIGNALS_HI[signal.id]?.label ?? signal.label,
      detail: PHONE_SIGNALS_HI[signal.id]?.detail ?? signal.detail,
    })),
    nextSteps: result.nextSteps.map((step) => PHONE_STEP_HI[step] ?? step),
    notes: [...PHONE_NOTES_HI],
  };
}

