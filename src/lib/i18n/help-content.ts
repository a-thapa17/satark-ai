export interface PlanSelections {
  immediateDanger: boolean;
  moneyLost: boolean;
}

export function localizeEmergencyPlan(
  plan: EmergencyPlan,
  language: Language,
  selections: PlanSelections
): EmergencyPlan {
  if (language === "en") return plan;
  const scenarioText = HI_SCENARIOS[plan.scenario.id];
  const copy = HELP_COPY.hi.emergency;
  const steps: EmergencyPlanStep[] = plan.steps.map((step) => {
    const flag = FLAG_STEP_HI[step.detail];
    if (flag) {
      return { ...step, title: flag.title, detail: flag.detail };
    }
    const translated = ACTION_HI.get(step.detail);
    if (!translated) return step;
    return {
      ...step,
      title: translated.split(/[।.]/)[0]?.trim() || step.title,
      detail: translated,
    };
  });
  const headline = selections.immediateDanger
    ? copy.headlineDanger
    : selections.moneyLost
      ? copy.headlineMoney
      : copy.headlineDefault;
  return {
    ...plan,
    scenario: scenarioWithText(plan.scenario, scenarioText),
    headline,
    steps,
    evidenceToPreserve: [...scenarioText.evidenceToPreserve],
    reportingOptions: scenarioText.reportingOptions.map((option) => ({
      ...option,
      resourceIds: [...option.resourceIds] as OfficialResourceId[],
    })),
    finalStep: selections.moneyLost
      ? `${scenarioText.finalStep} ${copy.finalSuffix}`
      : scenarioText.finalStep,
    noReportSubmitted: copy.noReport,
    recoveryDisclaimer: copy.recovery,
  };
}

