export function localizeOfficialResource(
  resource: OfficialResource,
  language: Language
): OfficialResource {
  if (language === "en") return resource;
  return { ...resource, ...HI_RESOURCES[resource.id] };
}

export function getLocalizedOfficialResources(
  ids: readonly OfficialResourceId[],
  language: Language
): OfficialResource[] {
  const seen = new Set<OfficialResourceId>();
  const result: OfficialResource[] = [];
  for (const id of ids) {
    if (seen.has(id)) continue;
    const resource = OFFICIAL_RESOURCES.find((item) => item.id === id);
    if (!resource) continue;
    seen.add(id);
    result.push(localizeOfficialResource(resource, language));
  }
  return result;
}

